/// Computes the deterministic 3-word Short Authentication String (SAS)
/// from two public keys or a handshake hash.
pub fn derive_confirmation_phrase(key_a: &str, key_b: &str) -> String {
    let mut keys = [key_a.trim().to_lowercase(), key_b.trim().to_lowercase()];
    keys.sort();
    let digest = blake3::hash(format!("{}:{}", keys[0], keys[1]).as_bytes());
    let bytes = digest.as_bytes();

    let w1 = SAS_WORDLIST[bytes[0] as usize];
    let w2 = SAS_WORDLIST[bytes[1] as usize];
    let w3 = SAS_WORDLIST[bytes[2] as usize];

    format!("{} · {} · {}", w1, w2, w3)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn wordlist_has_256_entries() {
        assert_eq!(SAS_WORDLIST.len(), 256);
    }

    #[test]
    fn phrase_is_order_independent_and_deterministic() {
        let key_1 = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";
        let key_2 = "fedcba9876543210fedcba9876543210fedcba9876543210fedcba9876543210";

        let phrase_a = derive_confirmation_phrase(key_1, key_2);
        let phrase_b = derive_confirmation_phrase(key_2, key_1);

        assert_eq!(phrase_a, phrase_b);
        assert_eq!(phrase_a.split(" · ").count(), 3);
    }
}
